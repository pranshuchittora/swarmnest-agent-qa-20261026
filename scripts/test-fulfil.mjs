ok(sessionToSlug(sess)===PRICE_TO_SLUG[price],'paid->slug');
ok(sessionToSlug({...sess,payment_status:'unpaid'})===null,'unpaid rejected');
ok(sessionToSlug({...sess,line_items:{data:[{price:{id:'price_x'}}]}})===null,'unknown price rejected');
