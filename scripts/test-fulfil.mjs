import { verifyStripeSignature, sessionToSlug, grantForSession } from '../functions/_lib/fulfil.js';
import { PRICE_TO_SLUG } from '../functions/_lib/prices.js';
import { createHmac } from 'crypto';
const ok=(c,n)=>{console.log(c?'PASS':'FAIL',n); if(!c) process.exitCode=1;};
const secret='whsec_test', body='{"a":1}', t=Math.floor(Date.now()/1000);
const sig=createHmac('sha256',secret).update(`${t}.${body}`).digest('hex');
ok(await verifyStripeSignature(body,`t=${t},v1=${sig}`,secret),'valid sig');
ok(!await verifyStripeSignature(body,`t=${t},v1=${sig.replace(/.$/,'0')}`,secret),'bad sig');
ok(!await verifyStripeSignature(body+' ',`t=${t},v1=${sig}`,secret),'tampered body');
ok(!await verifyStripeSignature(body,`t=${t-1000},v1=${createHmac('sha256',secret).update(`${t-1000}.${body}`).digest('hex')}`,secret),'stale');
const price=Object.keys(PRICE_TO_SLUG)[0];
